#!/usr/bin/env python3
"""Project a PDDL domain to OWL+SHACL Turtle. Deterministic: sorted, no timestamps."""
import re, sys, hashlib

def tokenize(s):
    s = re.sub(r";[^\n]*", "", s)
    return re.findall(r"\(|\)|[^\s()]+", s)

def parse(toks):
    stack = [[]]
    for t in toks:
        if t == "(":
            stack.append([])
        elif t == ")":
            x = stack.pop(); stack[-1].append(x)
        else:
            stack[-1].append(t.lower())
    return stack[0][0]

def typed(items):
    """['a','b','-','t','c'] -> [(a,t),(b,t),(c,object)]"""
    out, pend, i = [], [], 0
    while i < len(items):
        if items[i] == "-":
            out += [(n, items[i + 1]) for n in pend]; pend = []; i += 2
        else:
            pend.append(items[i]); i += 1
    return out + [(n, "object") for n in pend]

def walk(x):
    if isinstance(x, list):
        yield x
        for y in x:
            yield from walk(y)

def atoms(x, neg=False):
    """yield (name, negated) for predicate atoms under x."""
    if isinstance(x, list) and x:
        if x[0] == "not":
            yield from atoms(x[1], not neg)
        elif isinstance(x[0], str) and x[0] in ("and", "or", "at", "over", "forall", "when"):
            for y in x[1:]:
                if isinstance(y, list):
                    yield from atoms(y, neg)
        elif isinstance(x[0], str):
            yield (x[0], neg)

def iri(n):
    return re.sub(r"[^A-Za-z0-9_]", "_", n)

def camel(n):
    return "".join(p.capitalize() for p in re.split(r"[_\-]", n))

def main(src, dst):
    text = open(src).read()
    sha = hashlib.sha256(text.encode()).hexdigest()
    dom = parse(tokenize(text))
    sec = {}
    for s in dom[2:]:
        if isinstance(s, list) and s and s[0].startswith(":"):
            sec.setdefault(s[0], []).append(s)
    name = dom[1][1]
    types = typed(sec[":types"][0][1:])
    preds = [(p[0], typed(p[1:])) for p in sec[":predicates"][0][1:]]
    L = []
    w = L.append
    w("@prefix : <https://servengine.example/ontology#> .")
    w("@prefix owl: <http://www.w3.org/2002/07/owl#> .")
    w("@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .")
    w("@prefix sh: <http://www.w3.org/ns/shacl#> .")
    w("@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .")
    w("")
    w(f"# GENERATED by scripts/pddl_to_ttl.py from spec/{src.split('/')[-1]} -- do not edit")
    w("<https://servengine.example/ontology> a owl:Ontology ;")
    w(f'  rdfs:label "{name}" ;')
    w(f'  rdfs:comment "source sha256 {sha}" .')
    w("")
    tnames = sorted({t for t, _ in types} | {p for _, p in types})
    tnames = [t for t in tnames if t != "object"]
    parent = {}
    for t, p in types:
        parent[t] = p
    w("## Classes")
    for t in tnames:
        line = f":{camel(t)} a owl:Class ; rdfs:label \"{t}\""
        p = parent.get(t, "object")
        if p != "object":
            line += f" ; rdfs:subClassOf :{camel(p)}"
        w(line + " .")
    w("")
    w("## Predicates as properties")
    shapes = []
    for pn, params in sorted(preds):
        if len(params) >= 2:
            w(f":{iri(pn)} a owl:ObjectProperty ; rdfs:label \"{pn}\" ;")
            w(f"  rdfs:domain :{camel(params[0][1])} ; rdfs:range :{camel(params[1][1])} .")
            shapes.append((pn, params))
        elif len(params) == 1:
            w(f":{iri(pn)} a owl:DatatypeProperty ; rdfs:label \"{pn}\" ;")
            w(f"  rdfs:domain :{camel(params[0][1])} ; rdfs:range xsd:boolean .")
        else:
            w(f":{iri(pn)} a owl:DatatypeProperty ; rdfs:label \"{pn}\" ; rdfs:range xsd:boolean .")
    w("")
    w("## SHACL shapes (property range constraints)")
    for pn, params in shapes:
        w(f":{iri(pn)}Shape a sh:NodeShape ; sh:targetSubjectsOf :{iri(pn)} ;")
        w(f"  sh:property [ sh:path :{iri(pn)} ; sh:class :{camel(params[1][1])} ] .")
    w("")
    # WO state machine
    states = sorted({p for p, _ in preds if p.startswith("wo-state-")})
    w("## Work-order state machine")
    w(":WorkOrderState a owl:Class .")
    w(":Transition a owl:Class .")
    w(":fromState a owl:ObjectProperty ; rdfs:domain :Transition ; rdfs:range :WorkOrderState .")
    w(":toState a owl:ObjectProperty ; rdfs:domain :Transition ; rdfs:range :WorkOrderState .")
    w(":viaAction a owl:DatatypeProperty ; rdfs:domain :Transition ; rdfs:range xsd:string .")
    for s in states:
        w(f":{iri(s)} a :WorkOrderState ; rdfs:label \"{s[len('wo-state-'):]}\" .")
    acts = []
    for a in sec.get(":durative-action", []):
        an = a[1]
        cond = effe = None
        for i, k in enumerate(a):
            if k == ":condition": cond = a[i + 1]
            if k == ":effect": effe = a[i + 1]
        frm = sorted({n for n, ng in atoms(cond) if n.startswith("wo-state-") and not ng}) if cond else []
        pos = {n for n, ng in atoms(effe) if n.startswith("wo-state-") and not ng} if effe else set()
        neg = {n for n, ng in atoms(effe) if n.startswith("wo-state-") and ng} if effe else set()
        to = sorted(pos - neg)
        for f in frm:
            for t in to:
                acts.append((an, f, t))
    for an, f, t in sorted(acts):
        tn = f"tr_{iri(an)}_{iri(f)}_{iri(t)}"
        w(f":{tn} a :Transition ; :viaAction \"{an}\" ; :fromState :{iri(f)} ; :toState :{iri(t)} .")
    open(dst, "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
