"""Generate RULES-REPORT.md + rules.json by joining LAWS.md with facts extracted from code."""
import argparse
import ast
import inspect
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipeline" / "tests"))
import laws_ledger as ll  # noqa: E402

DOC = ROOT / "docs/jira/v26.11.11"
STORE = ROOT / "pipeline/enterprise_pipeline/store.py"
PDDL = ROOT / "spec/servengine_ideal_domain.pddl"
MZN = ROOT / "spec/alignment_dispatch.mzn"
ROSTER = ROOT / "pipeline/tests/avatar_roster.toml"
HEADER = "<!-- GENERATED by pipeline/rules_report.py; do not edit -->"
EXEMPT = {"OPEN", "UNSUPPORTED"}


def _kind_of(test):
    if (isinstance(test, ast.Compare) and isinstance(test.left, ast.Name)
            and test.left.id == "kind" and all(isinstance(o, ast.Eq) for o in test.ops)):
        return [c.value for c in test.comparators
                if isinstance(c, ast.Constant) and isinstance(c.value, str)]
    return []


def _prefix(call):
    if not call.args:
        return None
    a = call.args[0]
    s = a.value if isinstance(a, ast.Constant) and isinstance(a.value, str) else (
        a.values[0].value if isinstance(a, ast.JoinedStr) and a.values
        and isinstance(a.values[0], ast.Constant) else "")
    m = re.match(r"[A-Z_]+", s or "")
    return m.group(0) if m else None


def refused_prefixes(path=STORE):
    """{prefix: sorted kind branches of store.check enclosing a Refused(prefix)}; '' = no branch."""
    tree = ast.parse(Path(path).read_text())
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "check")
    out = {}

    def visit(node, ctx):
        if isinstance(node, ast.If):
            ks = _kind_of(node.test)
            visit(node.test, ctx)
            for c in node.body:
                visit(c, ks[0] if ks else ctx)
            for c in node.orelse:
                visit(c, ctx)
            return
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "Refused":
            p = _prefix(node)
            if p:
                out.setdefault(p, set()).add(ctx)
        for c in ast.iter_child_nodes(node):
            visit(c, ctx)

    for st in fn.body:
        visit(st, "")
    return {k: sorted(v) for k, v in sorted(out.items())}


def store_check_kinds(path=STORE):
    tree = ast.parse(Path(path).read_text())
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "check")
    ks = set()
    for n in ast.walk(fn):
        if isinstance(n, ast.If):
            ks.update(_kind_of(n.test))
    return sorted(ks)


def pddl_names(path=PDDL):
    txt = Path(path).read_text()
    actions = re.findall(r"\(:(?:durative-)?action\s+([\w-]+)", txt)
    m = re.search(r"\(:predicates(.*?)\(:functions", txt, re.S)
    preds = re.findall(r"^\s*\(([\w-]+)", m.group(1), re.M) if m else []
    return sorted(actions), sorted(preds)


def mzn_constraints(path=MZN):
    return [ln.strip() for ln in Path(path).read_text().splitlines()
            if ln.strip().startswith("constraint")]


def collect_nodes(target="pipeline/tests", root=ROOT):
    env = dict(os.environ, PYTHONPATH=f"{root}/pipeline:{root}/pipeline/tests")
    p = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q",
                        "-p", "no:cacheprovider", target],
                       cwd=root, env=env, capture_output=True, text=True)
    nodes = sorted({ln.strip() for ln in p.stdout.splitlines() if "::" in ln
                    and not ln.startswith(" ")})
    return nodes


def refs(cell, seps=r"[;,\s]+"):
    return [t for t in re.split(seps, cell.strip()) if t and t != "-"]


def resolve(laws, prefixes, kinds, actions, preds, nodes):
    """Per law: list of (column, ref, resolved). Test refs split on ';' only (node ids)."""
    out = {}
    nodeset = set(nodes)
    for lw in laws:
        rows = []
        for t in refs(lw.check):
            rows.append(("check", t, t in prefixes or t in kinds))
        for t in refs(lw.pddl):
            rows.append(("pddl", t, t in actions or t in preds))
        for t in refs(lw.test, r";"):
            t = t.strip()
            if t and t != "-":
                rows.append(("test", t, t in nodeset or any(
                    n.startswith(t + "::") or n.startswith(t + "[") for n in nodes)))
        out[lw.id] = rows
    return out


def roster_unsupported(path=ROSTER):
    return tomllib.loads(Path(path).read_text())["unsupported"]


def esc(s):
    return s.replace("|", "\\|")


def build(laws_path, open_path, collect="pipeline/tests"):
    laws = ll.parse_laws(Path(laws_path).read_text())
    opens = ll.parse_open(Path(open_path).read_text())
    prefixes = refused_prefixes()
    kinds = store_check_kinds()
    actions, preds = pddl_names()
    mzn = mzn_constraints()
    nodes = collect_nodes(collect)
    res = resolve(laws, prefixes, kinds, actions, preds, nodes)
    unresolved = [(lw.id, c, r) for lw in laws if lw.status not in EXEMPT
                  for c, r, ok in res[lw.id] if not ok]
    cited = {r for rows in res.values() for c, r, _ in rows if c == "check"}
    orphans = sorted(p for p in prefixes if p not in cited)
    unsup = roster_unsupported()
    data = {"laws": [dict(vars(lw), refs=[{"col": c, "ref": r, "resolved": ok}
                                          for c, r, ok in res[lw.id]]) for lw in laws],
            "open": [vars(o) for o in opens],
            "refused": prefixes, "store_kinds": kinds, "pddl_actions": actions,
            "pddl_predicates": preds, "mzn_constraints": mzn,
            "pytest_nodes_collected": len(nodes), "orphans": orphans,
            "unresolved": [list(u) for u in unresolved], "unsupported_roles": unsup}
    L = [HEADER, "", "# RULES-REPORT", "",
         f"laws: {len(laws)} | open: {len(opens)} | refused prefixes: {len(prefixes)} | "
         f"pddl actions: {len(actions)} | predicates: {len(preds)} | mzn constraints: "
         f"{len(mzn)} | pytest nodes: {len(nodes)} | orphans: {len(orphans)} | "
         f"unresolved: {len(unresolved)}", "", "## Laws", "",
         "| id | status | law | line | check | pddl | test | scenario | expect |",
         "|---|---|---|---|---|---|---|---|---|"]
    for lw in laws:
        mark = lambda c: " ".join(  # noqa: E731
            f"{r}{'' if ok else ' (UNRESOLVED)'}" for cc, r, ok in res[lw.id] if cc == c) or "-"
        st = lw.status
        L.append("| " + " | ".join(esc(x) for x in (
            lw.id, st, lw.law, lw.line, mark("check"), mark("pddl"), mark("test"),
            lw.scenario, lw.expect)) + " |")
    L += ["", "## Refused prefixes (store.check)", "", "| prefix | kind branches | cited by |",
          "|---|---|---|"]
    for p, ks in prefixes.items():
        by = [lw.id for lw in laws if any(c == "check" and r == p for c, r, _ in res[lw.id])]
        L.append(f"| {p} | {', '.join(k or '(global)' for k in ks)} | {', '.join(by) or '-'} |")
    L += ["", "## Orphans (Refused prefixes no law cites)", ""] + (
        [f"- {o}" for o in orphans] or ["(none)"])
    L += ["", "## PDDL", "", "actions: " + ", ".join(actions), "",
          "predicates: " + ", ".join(preds), "", "## MiniZinc constraints", ""]
    L += [f"- `{c}`" for c in mzn]
    L += ["", f"## UNSUPPORTED roles ({len(unsup)})", "", "| role | reason |", "|---|---|"]
    L += [f"| {k} | {esc(v)} |" for k, v in unsup.items()]
    L += ["", "## OPEN", "", "| " + " | ".join(ll.OPEN_COLS) + " |",
          "|" + "---|" * len(ll.OPEN_COLS)]
    L += ["| " + " | ".join(esc(getattr(o, c)) for c in ll.OPEN_COLS) + " |" for o in opens]
    return "\n".join(L) + "\n", json.dumps(data, indent=2, sort_keys=True) + "\n", unresolved


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--laws", default=str(DOC / "LAWS.md"))
    ap.add_argument("--open", default=str(DOC / "OPEN.md"))
    ap.add_argument("--out-dir", default=str(DOC))
    ap.add_argument("--collect", default="pipeline/tests")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    md, js, unresolved = build(a.laws, a.open, a.collect)
    if unresolved:
        print("UNRESOLVED references:", file=sys.stderr)
        for i, c, r in unresolved:
            print(f"  {i} {c}: {r}", file=sys.stderr)
        return 1
    out = Path(a.out_dir)
    if a.check:
        bad = [n for n, t in (("RULES-REPORT.md", md), ("rules.json", js))
               if not (out / n).exists() or (out / n).read_text() != t]
        if bad:
            print(f"DIFF: {', '.join(bad)} stale; run just rules-report", file=sys.stderr)
            return 1
        print("rules-report: up to date")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    (out / "RULES-REPORT.md").write_text(md)
    (out / "rules.json").write_text(js)
    print(f"wrote {out / 'RULES-REPORT.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
