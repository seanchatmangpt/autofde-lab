def _never(
    original: bytes, generated: bytes, context: Mapping[str, Any]
) -> VerifierResult:
    raise IECRefusal(
        "BLOCKED_EXECUTION_AUTHORITY", "this verifier only runs under a broker"
    )


NATIVE_VERIFIER_SET = VerifierSet(
    "ggen_igniter-native/1",
    (
        Verifier("mix-format-check-formatted", "1", "build", _never),
        Verifier("mix-compile-warnings-as-errors", "1", "build", _never),
        Verifier("mix-test", "1", "tests", _never),
    ),
)


def _template_literals(
    original: bytes, generated: bytes, context: Mapping[str, Any]
) -> VerifierResult:
    containment = literal_containment(context["chunks"], generated.decode("utf-8"))
    verdict = Verdict.PASS if containment.holds else Verdict.COUNTEREXAMPLE
    return VerifierResult(verdict, containment.detail, containment.to_json())


def _template_literals_modulo(
    original: bytes, generated: bytes, context: Mapping[str, Any]
) -> VerifierResult:
    containment = normalized_containment(
        context["chunks"], generated.decode("utf-8"), strip_whitespace_and_call_parens
    )
    verdict = Verdict.PASS if containment.holds else Verdict.COUNTEREXAMPLE
    return VerifierResult(
        verdict,
        containment.detail
        + " (after deleting whitespace and call parentheses on both sides)",
        containment.to_json(),
    )


def _row_heldout(
    original: bytes, generated: bytes, context: Mapping[str, Any]
) -> VerifierResult:
    results = context["heldout"]
    failed = [result for result in results if result["verdict"] != "PASS"]
    if failed:
        return VerifierResult(
            Verdict.COUNTEREXAMPLE,
            f"{len(failed)} of {len(results)} held-out rows not predicted from kernel facts",
            {"failed": failed},
        )
    return VerifierResult(
        Verdict.PASS,
        f"{len(results)} of {len(results)} rows predicted from a template learned without them",
    )


