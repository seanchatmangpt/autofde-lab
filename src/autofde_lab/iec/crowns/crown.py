"""IEC-C1: decompile, regenerate, and translation-validate one exact repository subject.

ARD section 25, step for step, against the committed generated outputs of one
frozen commit:

1. freeze the exact subject (`corpus.freeze_corpus`);
2. census it from the git object database (`census.census`);
3. classify origins, using the generators' own declarations (`generators`);
4. recover each output's kernel from its producer's ontology and gates, with an
   independent SPARQL engine (`kernel.pack_kernel`), and decompile the output
   into residue + kernel bindings (`decompile`);
5. prefer the existing generator; where it may not run here, say so as a typed
   `BLOCKED` court, not a silent substitution;
6. regenerate every subject into an isolated destination, from kernel + program
   only;
7. run the declared verifier sets against original and regenerated bytes;
8. preserve every mismatch as a counterexample;
9. refine a falsified hypothesis once, on new evidence, and record both courts;
10. emit translation-validation receipts, hypotheses, and promotion candidates.

Nothing here writes into the subject repository. The regenerated tree's identity
is checked by recomputing git tree ids in Python (`census.tree_id`).

Run from the command line:

    python -m autofde_lab.iec.crowns.crown --checkout ~/ggen_igniter --out receipts/v26.9.23/iec/c1
"""

