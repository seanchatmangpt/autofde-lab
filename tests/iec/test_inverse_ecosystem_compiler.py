def test_hypothesis_frontier_requires_change_after_counterexample() -> None:
    frontier = HypothesisFrontier()
    hypothesis = frontier.add(
        Hypothesis(
            covered_observation_ids=("o1",),
            excluded_observation_ids=(),
            kernel_delta={"rule": "a"},
            generator_delta={"template": "a"},
            required_residue=(),
            predicted_consequences=("same-output",),
            falsifier="translation validation mismatch",
            estimated_cost=1.0,
        )
    )
    counterexample = Counterexample(
        hypothesis_id=hypothesis.hypothesis_id,
        dimension=EquivalenceDimension.SYNTAX,
        verifier_id="exact/v1",
        expected="a",
        actual="b",
        detail="mismatch",
    )
    falsified = frontier.falsify(hypothesis.hypothesis_id, counterexample)
    with pytest.raises(ValueError, match="unchanged failed hypothesis"):
        frontier.refine(
            falsified.hypothesis_id,
            kernel_delta={"rule": "a"},
            generator_delta={"template": "a"},
            required_residue=(),
            predicted_consequences=("same-output",),
            falsifier="same falsifier",
            estimated_cost=1.0,
        )


