def test_engine_composes_pure_first_slice_end_to_end() -> None:
    compiler = InverseEcosystemCompiler(correspondence_threshold=0.2)
    original = subject("seanchatmangpt/original", "1" * 40)
    generated = subject("seanchatmangpt/generated", "2" * 40)
    session = compiler.freeze((original, generated))

    session = compiler.observe(
        session,
        original,
        (
            PassiveFile("ontology/domain.ttl", b"@prefix ex: <urn:x:> ."),
            PassiveFile("src/generated.py", b"# GENERATED BY ggen\n"),
        ),
    )
    assert len(session.analyses) == 1
    assert session.analyses[0].artifacts[0].artifact_class is ArtifactClass.CANONICAL_SOURCE

    session = compiler.generalize(
        session,
        ({"name": "a", "port": 1}, {"name": "b", "port": 2}),
        member_ids=("a", "b"),
    )
    assert session.generalizations[-1].reconstruct(0) == {"name": "a", "port": 1}

    court = EquivalenceCourt()
    court.register(
        EquivalenceDimension.SYNTAX,
        "exact/v1",
        exact_equality_verifier,
    )
    session = compiler.validate(
        session,
        court=court,
        original_subject_id=original.subject_id,
        generated_subject_id=generated.subject_id,
        original={"api": ["x"]},
        generated={"api": ["x"]},
        dimensions=(EquivalenceDimension.SYNTAX,),
        claim_ceiling=ClaimCeiling.STRUCTURAL_EQUIVALENCE_ONLY,
    )
    assert session.validations[-1].passed

    session = compiler.observe_reasoning(
        session,
        identity="classify-artifact",
        occurrence_id="r1",
    )
    session = compiler.observe_reasoning(
        session,
        identity="classify-artifact",
        occurrence_id="r2",
    )
    session = compiler.bind_reasoning_replacement(
        session,
        identity="classify-artifact",
        deterministic_replacement="ObservationExtractor.classify",
        verifier_id="iec-tests/v1",
    )
    session = compiler.retire_reasoning(
        session,
        identity="classify-artifact",
        replay_receipt="receipt:replay-ok",
        equivalent=True,
    )
    assert session.reasoning_classes[-1].status is RetirementStatus.RETIRED_FROM_LLM
