def test_retirement_requires_recurrence_replacement_and_replay() -> None:
    ledger = RetirementLedger(recurrence_threshold=2)
    first = ledger.observe("classify-generated-source", "o1")
    assert first.status is RetirementStatus.OBSERVED_ONCE
    second = ledger.observe("classify-generated-source", "o2")
    assert second.status is RetirementStatus.MECHANIZATION_CANDIDATE

    mechanized = ledger.bind_replacement(
        "classify-generated-source",
        deterministic_replacement="ObservationExtractor.classify",
        verifier_id="iec-test/v1",
    )
    assert mechanized.status is RetirementStatus.MECHANIZED

    failed = ledger.verify_replay(
        "classify-generated-source",
        replay_receipt="failed-run",
        equivalent=False,
    )
    assert failed.status is RetirementStatus.MECHANIZED

    retired = ledger.verify_replay(
        "classify-generated-source",
        replay_receipt="receipt:ok",
        equivalent=True,
    )
    assert retired.status is RetirementStatus.RETIRED_FROM_LLM


def preservation_fence() -> PreservationFence:
    return PreservationFence(
        system="example repository",
        boundary="public API",
        origin="historical implementation",
        function="manufacture example",
        consumers=("consumer-a",),
        authority="SELECT/CONSTRUCT only",
        compatibility=("api/v1",),
        historical_reason="original implementation",
        replacement_path="ggen-marketplace:example-pack",
        rollback_path="restore exact git subject",
    )


def test_destructive_disposition_requires_replacement_rollback_and_verifier() -> None:
    fence = preservation_fence()
    court = DispositionCourt()
    candidate = court.propose(
        subject_id="subject",
        disposition=Disposition.ARCHIVE,
        reason="replacement translation-validated",
        fence=fence,
        verifier_set_ids=("verifier-set",),
    )
    assert candidate.standing == "CANDIDATE"
    assert candidate.authority_required == "BRCE"

    bad_fence = PreservationFence(
        system=fence.system,
        boundary=fence.boundary,
        origin=fence.origin,
        function=fence.function,
        consumers=fence.consumers,
        authority=fence.authority,
        compatibility=fence.compatibility,
        historical_reason=fence.historical_reason,
        replacement_path=None,
        rollback_path=fence.rollback_path,
    )
    with pytest.raises(ValueError, match="replacement path required"):
        court.propose(
            subject_id="subject",
            disposition=Disposition.DELETE,
            reason="looks redundant",
            fence=bad_fence,
            verifier_set_ids=("verifier-set",),
        )


def test_kernel_dominance_requires_same_proof_obligations() -> None:
    base = dict(
        covered_observation_ids=("o1", "o2"),
        verifier_set_ids=("v1",),
        preservation_fence_ids=("f1",),
    )
    left = KernelCandidate(
        kernel_id="small",
        cost=CostVector(1, 1, 0, 0, 0),
        **base,
    )
    right = KernelCandidate(
        kernel_id="large",
        cost=CostVector(10, 2, 1, 1, 0),
        **base,
    )
    assert dominates(left, right)

    incomparable = KernelCandidate(
        kernel_id="different-proof",
        covered_observation_ids=base["covered_observation_ids"],
        verifier_set_ids=("v2",),
        preservation_fence_ids=base["preservation_fence_ids"],
        cost=CostVector(0, 0, 0, 0, 0),
    )
    assert not dominates(incomparable, right)


def test_incremental_cache_invalidates_dependents_transitively() -> None:
    cache = ObservationCache()
    root = CacheKey("s", "parser", "1", "input-a")
    child = CacheKey("s", "semantic", "1", "input-b")
    grandchild = CacheKey("s", "kernel", "1", "input-c")
    cache.put(CacheEntry(root, "out-root"))
    cache.put(CacheEntry(child, "out-child", (root.key,)))
    cache.put(CacheEntry(grandchild, "out-grandchild", (child.key,)))
    invalidated = cache.invalidate(root)
    assert invalidated == tuple(sorted((root.key, child.key, grandchild.key)))
    assert cache.identities() == ()


