def subject(
    name: str = "seanchatmangpt/example",
    revision: str = "a" * 40,
    visibility: str = "public",
) -> RepositorySubject:
    return RepositorySubject(
        repository=name,
        revision=revision,
        default_branch="main",
        visibility=visibility,
    )


def test_subject_identity_is_deterministic_and_revision_bound() -> None:
    left = subject()
    right = subject()
    moved = subject(revision="b" * 40)
    assert left.subject_id == right.subject_id
    assert left.subject_id != moved.subject_id


def test_corpus_freeze_refuses_private_identity_by_default() -> None:
    freezer = CorpusFreezer()
    with pytest.raises(PermissionError, match="REFUSED_PRIVATE_IDENTITY_LEAK"):
        freezer.freeze([subject(visibility="private")])


def test_corpus_freeze_refuses_duplicate_repository_subjects() -> None:
    freezer = CorpusFreezer()
    with pytest.raises(ValueError, match="duplicate repository identity"):
        freezer.freeze([subject(), subject(revision="b" * 40)])


def test_corpus_compare_names_moved_subject_as_topology_failure() -> None:
    freezer = CorpusFreezer()
    prior = freezer.freeze([subject()])
    current = freezer.freeze([subject(revision="b" * 40)])
    failures = freezer.compare(prior, current)
    assert len(failures) == 1
    assert failures[0].kind.value == "BLOCKED_CORPUS_IDENTITY"
    assert "repository moved" in failures[0].detail


