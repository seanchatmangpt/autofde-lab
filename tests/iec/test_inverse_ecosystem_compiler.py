def test_anti_unification_reconstructs_every_member() -> None:
    members = [
        {"name": "alpha", "port": 1, "flags": ["x", True]},
        {"name": "beta", "port": 2, "flags": ["x", False]},
        {"name": "gamma", "port": 3, "flags": ["x", True]},
    ]
    result = AntiUnifier().generalize(
        members,
        member_ids=("a", "b", "c"),
    )
    assert [result.reconstruct(i) for i in range(3)] == members
    assert result.template["flags"][0] == "x"
    assert result.template["name"] != "alpha"


def test_anti_unification_generalizes_whole_incompatible_shape() -> None:
    members = [{"x": 1}, {"x": 1, "y": 2}]
    result = AntiUnifier().generalize(members)
    assert result.reconstruct(0) == members[0]
    assert result.reconstruct(1) == members[1]


def test_correspondence_similarity_remains_candidate() -> None:
    engine = CorrespondenceEngine(threshold=0.3)
    candidates = engine.lexical_candidates(
        [
            ("a", "authority receipt replay standing", ("ev-a",)),
            ("b", "authority receipt replay verifier", ("ev-b",)),
        ]
    )
    assert len(candidates) == 1
    candidate = candidates[0]
    assert candidate.relation.endswith("Candidate")
    assert "similarity_is_not_equivalence" in candidate.exclusions
    assert candidate.required_verifier == "iec.translation-validation"


def test_equivalence_court_preserves_counterexample() -> None:
    court = EquivalenceCourt()
    court.register(
        EquivalenceDimension.SYNTAX,
        "exact/v1",
        exact_equality_verifier,
    )
    result = court.validate(
        original_subject_id="original",
        generated_subject_id="generated",
        original={"x": 1},
        generated={"x": 2},
        dimensions=(EquivalenceDimension.SYNTAX,),
        claim_ceiling=ClaimCeiling.STRUCTURAL_EQUIVALENCE_ONLY,
    )
    assert not result.passed
    assert len(result.counterexamples) == 1
    assert result.counterexamples[0].expected == {"x": 1}
    assert result.counterexamples[0].actual == {"x": 2}


