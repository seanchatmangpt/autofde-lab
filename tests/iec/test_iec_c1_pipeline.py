def test_row_program_units(tmp_path):
    rows = [
        {
            "number": "0002",
            "filename": "0002-b.md",
            "title": "Ay",
            "status": "Accepted",
        },
        {
            "number": "0001",
            "filename": "0001-a.md",
            "title": "Mid",
            "status": "Accepted",
        },
        {
            "number": "0003",
            "filename": "0003-c.md",
            "title": "Zed",
            "status": "Accepted",
        },
    ]
    text = (
        "head\n"
        + "".join(
            f"| [{r['number']}]({r['filename']}) | {r['title']} | {r['status']} |\n"
            for r in sorted(rows, key=lambda r: r["number"])
        )
        + "tail\n"
    )
    program = row_program(text, "adrs", rows)
    assert (
        template_text(program.row_template)
        == "| [{{X0}}]({{X1}}) | {{X2}} | Accepted |\n"
    )
    assert program.hole_variables == {0: ["number"], 1: ["filename"], 2: ["title"]}
    # titles do not sort in number order, so only number and filename survive
    assert set(program.order_hypotheses) == {"number", "filename"}
    assert program.constant_literals == ({"variable": "status", "value": "Accepted"},)
    assert program.regenerate(rows) == text
    assert all(
        result["verdict"] == "PASS" for result in leave_one_out(text, "adrs", rows)
    )
    with pytest.raises(IECRefusal):
        row_program("no rows here\n", "adrs", rows)


def test_flat_program_refuses_ambiguous_regeneration():
    program = flat_program(
        "x = shared; y = shared\n", {"k:a": "shared", "k:b": "shared"}
    )
    assert program.coverage()["ambiguous_holes"] == 2
    assert (
        program.regenerate({"k:a": "shared", "k:b": "shared"})
        == "x = shared; y = shared\n"
    )
    with pytest.raises(IECRefusal) as refused:
        program.regenerate({"k:a": "one", "k:b": "two"})
    assert refused.value.code == "UNKNOWN_EQUIVALENCE"


def test_declared_outputs_cover_eex_and_ggen_toml_and_flag_contests(tmp_path):
    files = fixture_files()
    files["ggen.toml"] = (
        '[generation]\noutput_dir = "."\n\n[[generation.rules]]\nname = "idx"\n'
        'query = { file = "q.rq" }\ntemplate = { file = "t.tera" }\n'
        'output_file = "docs/INDEX.md"\nmode = "Overwrite"\n'
    )
    repo = make_repo(tmp_path / "repo", files)
    frozen = observe_checkout(
        repo,
        repository=REPOSITORY,
        branch="main",
        visibility="public",
        inclusion_reason="t",
    )
    base = census(frozen, repo)
    outputs = declared_outputs(base, repo)
    assert {(o.syntax, o.target) for o in outputs} >= {
        ("eex-frontmatter", "docs/INDEX.md"),
        ("ggen-toml-rule", "docs/INDEX.md"),
        ("eex-frontmatter", "lib/demo/alpha.ex"),
    }
    targets = declared_targets(outputs)
    assert targets["docs/INDEX.md"]["contested"] == "true"
    kernel = pack_kernel(base, repo, "priv/ggen/index-pack/templates/readme.md.eex")
    assert kernel.engine["name"] == "rdflib"
    # kernel rows are in canonical (content-id) order, not domain order
    assert sorted(row["number"] for row in kernel.rows["entries"]) == [
        "0001",
        "0002",
        "0003",
    ]
    assert kernel.declaration["template.to"] == "docs/INDEX.md"
