#!/usr/bin/env python3
"""
F05 — ReceiptCheck is not independent evidence. The receipt carries no
signature, no binding to a path/run, and is only compared against fields the
CLAIMANT wrote into the ref. Scenario:

  1. Issuer writes receipt R1 for artifact A (sha S1).           -> RESOLVED
  2. Artifact is regenerated (different bytes, sha S2).           -> DigestCheck refuses (good)
  3. Claimant writes a NEW receipt R2 with issuer="crown-2",
     subject_sha256=S2, and updates the ref's sha to S2.          -> RESOLVED again

R1 (unsuperseded, for S1) still exists; the target has no notion of "the
receipt on file for identity X" and cannot see that R2 was minted by the
claimant. Also: superseded_by="" (empty string) is treated as not superseded.

severity WEAKENS_CLAIM (receipt gate provides no adversarial guarantee).
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import cleanup, evidence, fresh_scratch, report, write  # noqa: E402

d = fresh_scratch("f05")
art = write(os.path.join(d, "hook.jsonl"), "\n".join('{"i": %d}' % i for i in range(82)) + "\n")
ref1 = evidence.make_ref("hook-run-82", art, "jsonl")
r1 = evidence.ArtifactReceipt("rcpt-1", "hook-run-82", ref1.sha256, "2026-09-01T00:00:00Z", "crown-2") \
    .write(os.path.join(d, "r1.json"))
s1 = evidence.resolve(evidence.EvidenceRef(*ref1.__dict__.values()).__class__(
    ref1.identity, ref1.durable_path, ref1.sha256, ref1.parser, r1))

# regenerate the artifact (83 records now)
write(art, "\n".join('{"i": %d}' % i for i in range(83)) + "\n")
s2 = evidence.resolve(evidence.EvidenceRef(ref1.identity, ref1.durable_path, ref1.sha256, ref1.parser, r1))

# claimant forges a fresh receipt for the regenerated bytes
ref2 = evidence.make_ref("hook-run-82", art, "jsonl")
r2 = evidence.ArtifactReceipt("rcpt-1", "hook-run-82", ref2.sha256, "2026-09-01T00:00:00Z", "crown-2") \
    .write(os.path.join(d, "r2.json"))
s3 = evidence.resolve(evidence.EvidenceRef(ref2.identity, ref2.durable_path, ref2.sha256, ref2.parser, r2))

# superseded_by="" passes as not-superseded
r3 = evidence.ArtifactReceipt("rcpt-1", "hook-run-82", ref2.sha256, "2026-09-01T00:00:00Z", "crown-2",
                              superseded_by="").write(os.path.join(d, "r3.json"))
s4 = evidence.resolve(evidence.EvidenceRef(ref2.identity, ref2.durable_path, ref2.sha256, ref2.parser, r3))

detail = (
    f"  1 original            : {s1.status}\n"
    f"  2 regenerated, old ref: {s2.status}\n"
    f"  3 regenerated, forged receipt (same receipt_id/issuer): {s3.status}\n"
    f"    r1 still on disk, unsuperseded, for sha {ref1.sha256[:12]} : {os.path.exists(r1)}\n"
    f"  4 superseded_by=''    : {s4.status}\n"
)
reproduced = (s1.resolved and s2.status == evidence.refusal("DigestCheck") and s3.resolved and s4.resolved)
report("receipt is claimant-forgeable; regenerated artifact re-earns standing", "WEAKENS_CLAIM", reproduced, detail)
cleanup("f05")
assert reproduced, "F05 did not reproduce"
